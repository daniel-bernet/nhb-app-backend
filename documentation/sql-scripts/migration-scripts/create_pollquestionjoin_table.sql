CREATE TABLE PollQuestionJoins (
    PollQuestionID UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    PollID UUID NOT NULL REFERENCES Polls(PollID) ON DELETE CASCADE,
    QuestionID UUID NOT NULL REFERENCES Questions(QuestionID) ON DELETE CASCADE,
    createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updatedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
